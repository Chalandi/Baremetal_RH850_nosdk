//-----------------------------------------------------------------------------------------
// Includes
//-----------------------------------------------------------------------------------------
#include <stdint.h>

//-----------------------------------------------------------------------------------------
// Globals
//-----------------------------------------------------------------------------------------

//-----------------------------------------------------------------------------------------
// Function Prototypes
//-----------------------------------------------------------------------------------------
void timer_isr(void);
void ostm_init(void);
void ostm_start(void);
void ostm_reload(uint32_t reload_value);

//-----------------------------------------------------------------------------------------
// Defines
//-----------------------------------------------------------------------------------------
#define PORT_BASE  0xFFC10000ul
#define PMC(port) (*(volatile uint16_t*)(PORT_BASE + 0x400ul + (port * 4)))
#define  PM(port) (*(volatile uint16_t*)(PORT_BASE + 0x300ul + (port * 4)))
#define   P(port) (*(volatile uint16_t*)(PORT_BASE + 0x000ul + (port * 4)))

//----------------------------------------------------------------------------------------
/// \brief  
///
/// \descr 
///
/// \param  
///
/// \return 
//----------------------------------------------------------------------------------------
void main(void)
{
    /* configure and turn LED1 on */
    PM(10) &= (uint16_t)~(1ul << 3);
    P(10)   = (uint16_t)(1ul << 3);

    /* configure the OSTM0 timer */
    ostm_reload(24000000ul - 1);
    ostm_init();
    ostm_start();

    for(;;);
}

//----------------------------------------------------------------------------------------
/// \brief  
///
/// \descr  OSTM0 timer interrupt
///
/// \param  
///
/// \return 
//----------------------------------------------------------------------------------------
void timer_isr(void)
{
    /* toggle the LED1 */
    P(10) ^= (1u << 3);
}
